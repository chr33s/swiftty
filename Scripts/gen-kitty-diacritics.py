#!/usr/bin/env python3
"""Generates Sources/SwifttyEngine/Graphics/KittyDiacritics.swift.

Input is kitty's gen/rowcolumn-diacritics.txt (lines starting with a hex
codepoint, `0305;COMBINING OVERLINE;Mn;...`) or Ghostty's
src/terminal/kitty/graphics_unicode.zig, which embeds the same table.
The index of a codepoint in the list is the row/column value it encodes.

    Scripts/gen-kitty-diacritics.py rowcolumn-diacritics.txt
"""
import re
import sys

source = open(sys.argv[1], encoding="utf-8").read()
if "const diacritics" in source:
    body = source.split("const diacritics", 1)[1].split("};", 1)[0]
    points = [int(h, 16) for h in re.findall(r"0x([0-9A-Fa-f]+)", body)]
else:
    points = [
        int(line.split(";", 1)[0], 16)
        for line in source.splitlines()
        if re.match(r"^[0-9A-Fa-f]{4,6};", line)
    ]
assert len(points) == 297, len(points)
assert points == sorted(points)

rows = []
for i in range(0, len(points), 8):
    rows.append("    " + ", ".join(f"0x{p:04X}" for p in points[i : i + 8]) + ",")
out = f"""// Generated by Scripts/gen-kitty-diacritics.py; do not edit.
// kitty's rowcolumn-diacritics.txt: the index of a codepoint is the row,
// column or high image-id byte a Unicode placeholder cell encodes.

extension KittyGraphics {{
  public static let diacritics: [UInt32] = [
{chr(10).join(rows)}
  ]
}}
"""
open("Sources/SwifttyEngine/Graphics/KittyDiacritics.swift", "w").write(out)
